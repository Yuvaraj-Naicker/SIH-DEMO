import { LocationConfig, SensorNode, MonitoredArea } from '../types';

// Helper to build realistic 1 Internal Node + 4 Leaf Nodes per monitored area
// with strictly landward coordinates (no nodes in sea), overlapping radii, and resilient mesh hopping paths
function createAreaNodes(
  areaId: string,
  areaName: string,
  centerLat: number,
  centerLng: number,
  baseRainfall: number,
  baseWaterLevel: number,
  soilMoisture?: number,
  windKmh = 22
): SensorNode[] {
  // Extract area numeric index from areaId (e.g. 'pud-area-2' -> 2)
  const numMatch = areaId.match(/(\d+)$/);
  const areaIndex = numMatch ? parseInt(numMatch[1], 10) : 1;

  // Geographic boundary clamping to guarantee NO node appears in the sea
  // Clamps coordinates to ensure they stay on land within monitored corridors
  const clampToLand = (lat: number, lng: number): { lat: number; lng: number } => {
    let cLat = lat;
    let cLng = lng;

    // Puducherry bounds (Bay of Bengal is to the East)
    if (cLat >= 11.80 && cLat <= 12.08) {
      if (cLng > 79.8350) cLng = 79.8325;
    }
    // Chennai bounds (Bay of Bengal is to the East)
    if (cLat >= 12.80 && cLat <= 13.25) {
      if (cLng > 80.2720) cLng = 80.2640;
    }
    // Mumbai bounds (Arabian Sea is to the West)
    if (cLat >= 18.85 && cLat <= 19.35) {
      if (cLng < 72.8250) cLng = 72.8310;
    }
    // Kerala bounds (Arabian Sea is to the West)
    if (cLat >= 8.30 && cLat <= 12.60) {
      if (cLng < 76.220) cLng = 76.260;
    }

    return {
      lat: Number(cLat.toFixed(5)),
      lng: Number(cLng.toFixed(5)),
    };
  };

  // Keep exactly 6 internal gateway nodes across the six monitored areas,
  // but separate each gateway slightly from the area's center so the nodes
  // are visually distinct while their 1.85 km coverage circles still overlap.
  const internalSpread = [
    { dLat: +0.0060, dLng: -0.0050 },
    { dLat: -0.0055, dLng: +0.0060 },
    { dLat: +0.0050, dLng: +0.0060 },
    { dLat: -0.0060, dLng: -0.0055 },
    { dLat: +0.0065, dLng: +0.0045 },
    { dLat: -0.0045, dLng: -0.0065 },
  ];
  const internalOffset = internalSpread[(areaIndex - 1) % internalSpread.length];
  const internalCoords = clampToLand(
    centerLat + internalOffset.dLat,
    centerLng + internalOffset.dLng
  );
  const internalNodeId = `${areaId}-INT-1`;
  const internalCode = `IN-0${areaIndex}`;

  // Use distinct nearby locality names for each node instead of repeating
  // the monitored-area name on every internal/leaf node card.
  const nodePlaceNames: Record<string, string[]> = {
    'bom-area-1': ['Kurla', 'Saki Naka', 'Chunabhatti', 'Nehru Nagar', 'Kalina'],
    'bom-area-2': ['Dadar', 'Hindmata', 'Parel', 'Naigaon', 'Prabhadevi'],
    'bom-area-3': ['Santacruz', 'Vile Parle', 'Vakola', 'Khar East', 'Bandra East'],
    'bom-area-4': ['Sion', 'Chunabhatti', 'Wadala', 'Antop Hill', 'Matunga East'],
    'bom-area-5': ['Dharavi', 'Mahim', 'Bandra West', 'Mahim Causeway', 'Shivaji Park'],
    'bom-area-6': ['BKC', 'Kurla West', 'Kalina', 'Bandra East', 'Mithi Confluence'],
    'ker-area-1': ['Aluva', 'Companypady', 'Aluva Palace', 'Choondy', 'Aluva Market'],
    'ker-area-2': ['Desom', 'Chengamanad', 'Nedumbassery', 'Athani', 'Paravur Road'],
    'ker-area-3': ['Choornikkara', 'Thaikkattukara', 'Ambattukavu', 'Kariyad', 'Thottumugham'],
    'ker-area-4': ['Eloor', 'Udyogamandal', 'Edayar', 'Manjummel', 'Cheranalloor'],
    'ker-area-5': ['Kalamassery', 'Muttar', 'HMT Junction', 'Pathadipalam', 'South Kalamassery'],
    'ker-area-6': ['Nedumbassery', 'Athani', 'Chengamanad', 'Karayamparambu', 'Parakkulam'],
    'che-area-1': ['Saidapet', 'Guindy', 'Jafferkhanpet', 'Little Mount', 'Nandanam'],
    'che-area-2': ['Jafferkhanpet', 'Ashok Nagar', 'K. K. Nagar', 'MGR Nagar', 'West Mambalam'],
    'che-area-3': ['T. Nagar', 'Panagal Park', 'Kodambakkam', 'Nungambakkam', 'West Mambalam'],
    'che-area-4': ['Kotturpuram', 'Adyar', 'Gandhi Nagar', 'Raja Annamalaipuram', 'Adambakkam'],
    'che-area-5': ['Mylapore', 'Mandaveli', 'R. A. Puram', 'Santhome', 'Alwarpet'],
    'che-area-6': ['Guindy', 'Kathipara', 'Alandur', 'St. Thomas Mount', 'Ekkatuthangal'],
    'pud-area-1': ['Mudaliarpet', 'Velrampet', 'Murungapakkam', 'Nellithope', 'Ariyankuppam'],
    'pud-area-2': ['Reddiarpalayam', 'Moolakulam', 'Lawspet', 'Mettupalayam', 'Dasan Nagar'],
    'pud-area-3': ['Ozhukarai', 'Thilaspet', 'Brindavanam', 'Lawspet', 'Rainbow Nagar'],
    'pud-area-4': ['White Town', 'Grand Bazaar', 'Heritage Town', 'Mission Street', 'MG Road Area'],
    'pud-area-5': ['Villianur', 'Sultanpet', 'Ariyur', 'Thirubuvanai', 'Kandamangalam'],
    'pud-area-6': ['Ariyankuppam', 'Chunnambar', 'Nonankuppam', 'Manapet', 'Kirumampakkam'],
  };
  const nodePlaces = nodePlaceNames[areaId] ?? [areaName, areaName, areaName, areaName, areaName];

  // Next hop for Internal Gateway Router:
  // Area 1 is the primary uplink coordinator (direct cloud backhaul).
  // Area 2+ hop to Area 1 or previous Area's gateway router to form a continuous city-wide mesh.
  const basePrefix = areaId.replace(/-\d+$/, '');
  const nextHopInternal = areaIndex === 1 ? undefined : `${basePrefix}-${areaIndex - 1}-INT-1`;

  // 1 INTERNAL NODE (Gateway Router) — one per monitored area; 6 total in the active city
  const internalNode: SensorNode = {
    id: internalNodeId,
    code: internalCode,
    name: `${nodePlaces[0]} (${internalCode})`,
    type: 'internal',
    areaId,
    lat: internalCoords.lat,
    lng: internalCoords.lng,
    elevationM: 14 + areaIndex * 2,
    coverageRadiusKm: 1.85, // Generous overlapping coverage radius (~1.85km) intersecting adjacent areas
    hardwareModel: 'TW-GW400 Dual-LoRaWAN Mesh Gateway',
    sensorTypes: ['Dual-LoRaWAN Mesh Router', 'Barometric Temp/Humidity', 'Gateway Uplink 4G/NB-IoT'],
    batteryPercent: 94 - (areaIndex % 3),
    solarVoltageV: 4.15,
    rssiDbm: -68 - (areaIndex * 2),
    packetLossPercent: 0.15,
    lastPingSecAgo: 3 + areaIndex,
    hopsToGateway: areaIndex === 1 ? 0 : 1,
    nextHopNodeId: nextHopInternal,
    status: 'online',
    readings: {
      rainfallMmH: Number((baseRainfall * 0.98).toFixed(1)),
      waterLevelM: Number((baseWaterLevel * 0.98).toFixed(2)),
      ambientTempC: 28.2,
      humidityPercent: 86,
      windSpeedKmh: windKmh,
      soilMoisturePercent: soilMoisture ? Math.min(100, Math.round(soilMoisture)) : undefined,
    },
  };

  // 4 LEAF NODES (Field Sensor Probes)
  // Four-direction natural spread (~450m - 750m) ensuring overlapping coverage with internal node and adjacent leaf nodes
  const leafScatter = [
    { dLat: +0.0052, dLng: -0.0042, label: 'Ultrasonic Stage Gauge' },
    { dLat: -0.0048, dLng: +0.0042, label: 'Tipping Bucket Rain Gauge' },
    { dLat: +0.0044, dLng: +0.0045, label: 'Soil Saturation & Pore Probe' },
    { dLat: -0.0050, dLng: -0.0044, label: 'Optical Velocity & Depth Sensor' },
  ];

  const startLeafNum = (areaIndex - 1) * 4 + 1;
  const leafNodes: SensorNode[] = leafScatter.map((off, idx) => {
    const leafNumber = startLeafNum + idx;
    const leafCode = `LN-${String(leafNumber).padStart(2, '0')}`;
    const leafId = `${areaId}-LEAF-${idx + 1}`;
    const rawCoords = clampToLand(centerLat + off.dLat, centerLng + off.dLng);

    return {
      id: leafId,
      code: leafCode,
      name: `${nodePlaces[idx + 1]} (${leafCode})`,
      type: 'leaf',
      areaId,
      lat: rawCoords.lat,
      lng: rawCoords.lng,
      elevationM: 10 + (idx * 3),
      coverageRadiusKm: 1.35, // Overlapping coverage with Internal Node and adjacent leaf nodes (~1.35km)
      hardwareModel: 'TW-SN100 Multi-Sensor LoRa Probe',
      sensorTypes: [off.label, 'Ambient Hydrometric Telemetry', 'LoRa 865MHz'],
      batteryPercent: 88 - (idx * 3),
      solarVoltageV: 3.9 - (idx * 0.05),
      rssiDbm: -76 - (idx * 3),
      packetLossPercent: Number((0.4 + idx * 0.2).toFixed(2)),
      lastPingSecAgo: 8 + idx * 4,
      hopsToGateway: 1,
      nextHopNodeId: internalNodeId, // Hopping directly to its area's internal gateway router
      status: 'online',
      readings: {
        rainfallMmH: Number((baseRainfall * (0.92 + idx * 0.05)).toFixed(1)),
        waterLevelM: Number((baseWaterLevel * (0.94 + idx * 0.04)).toFixed(2)),
        ambientTempC: Number((27.8 + idx * 0.3).toFixed(1)),
        humidityPercent: Math.min(98, 85 + idx * 2),
        windSpeedKmh: Number((windKmh + (idx - 1.5) * 1.2).toFixed(1)),
        soilMoisturePercent: soilMoisture ? Math.min(100, Math.round(soilMoisture + (idx * 2))) : undefined,
      },
    };
  });

  return [internalNode, ...leafNodes];
}

